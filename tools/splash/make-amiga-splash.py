#!/usr/bin/env python3
"""Convert tools/splash/unreal-splash.png into the embedded Amiga splash.

Output: Source/Unreal/Src/AmigaSplashData.h -- a 256-colour image (8-bit
pixel indices + 0x00RRGGBB palette) that AmigaSplash.c draws with
cybergraphics WriteLUTPixelArray, so it works on any RTG screen depth.
Requires Pillow.  Usage: python3 tools/splash/make-amiga-splash.py
"""
import os
import sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "tools", "splash", "unreal-splash.png")
DST = os.path.join(ROOT, "Source", "Unreal", "Src", "AmigaSplashData.h")

src = Image.open(sys.argv[1] if len(sys.argv) > 1 else SRC).convert("RGBA")
rgb = Image.new("RGB", src.size, (0, 0, 0))
rgb.paste(src, mask=src.split()[3])
img = rgb.quantize(256, method=Image.Quantize.MEDIANCUT,
                   dither=Image.Dither.FLOYDSTEINBERG)
w, h = img.size
pal = img.getpalette()[:256 * 3]
pal += [0] * (256 * 3 - len(pal))
pix = img.tobytes()

out = []
out.append("/* Generated by tools/splash/make-amiga-splash.py -- do not edit. */")
out.append("#define AMIGA_SPLASH_WIDTH  %d" % w)
out.append("#define AMIGA_SPLASH_HEIGHT %d" % h)
out.append("static const unsigned long AmigaSplashPalette[256] = {")
for i in range(0, 256, 8):
    out.append("  " + ",".join("0x%06x" % ((pal[j*3] << 16) | (pal[j*3+1] << 8) | pal[j*3+2])
                               for j in range(i, i + 8)) + ",")
out.append("};")
out.append("static const unsigned char AmigaSplashPixels[%d] = {" % (w * h))
for i in range(0, len(pix), 32):
    out.append("  " + ",".join(str(b) for b in pix[i:i + 32]) + ",")
out.append("};")
with open(DST, "w", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print("wrote %s (%dx%d)" % (DST, w, h))
